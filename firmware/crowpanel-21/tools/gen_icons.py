"""Turns the design's 24x24 stroke icons into panel_icons.h: flattened polylines, 1/8 unit steps, drawn on the panel with
lv_line (round caps, the stroke scales with the icon). Needs svg.path (pip install svg.path). Run on the sandbox:
  python3 tools/gen_icons.py > panel_icons.h
"""
import math, sys
from svg.path import parse_path, Line, Arc, CubicBezier, QuadraticBezier, Move, Close

def ellipse(cx, cy, rx, ry):
    return f"M{cx - rx} {cy} A{rx} {ry} 0 1 0 {cx + rx} {cy} A{rx} {ry} 0 1 0 {cx - rx} {cy}z"

def rect(x, y, w, h, r):
    return (f"M{x + r} {y} H{x + w - r} A{r} {r} 0 0 1 {x + w} {y + r} V{y + h - r} A{r} {r} 0 0 1 {x + w - r} {y + h} "
            f"H{x + r} A{r} {r} 0 0 1 {x} {y + h - r} V{y + r} A{r} {r} 0 0 1 {x + r} {y}z")

# name: (stroke width in 24-unit space, [path data...])
