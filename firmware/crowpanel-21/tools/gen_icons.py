def flatten(d):
    out, cur = [], []
    for seg in parse_path(d):
        if isinstance(seg, Move):
            if len(cur) > 1: out.append(cur)
            cur = [(seg.end.real, seg.end.imag)]
            continue
        if isinstance(seg, Line) or isinstance(seg, Close):
            pts = [seg.end]
        else:
            n = max(4, int(abs(seg.end - seg.start) / 1.2) + 4)
            if isinstance(seg, Arc): n = max(6, int(math.radians(abs(seg.delta)) * max(seg.radius.real, seg.radius.imag) / 0.8) + 2)
            pts = [seg.point(i / n) for i in range(1, n + 1)]
        if not cur: cur = [(seg.start.real, seg.start.imag)]
        cur.extend((p.real, p.imag) for p in pts)
    if len(cur) > 1: out.append(cur)
    return out

def q(v): return max(0, min(255, round(v * 8)))

print("#pragma once")
print("// Generated by tools/gen_icons.py from the design's 24x24 icons. Do not edit by hand.")
print("// Format per icon: number of lines, then per line a point count and x,y pairs in 1/8 units of the 24 grid.")
print("#include <cstdint>")
print("namespace panel {")
print("enum Icon : uint8_t { IC_NONE = 0, " + ", ".join(f"IC_{n}" for n, _, _ in ICONS) + ", IC_COUNT };")
for n, _, paths in ICONS:
    lines = [l for p in paths for l in flatten(p)]
    data = [len(lines)]
    for l in lines:
        data.append(len(l))
        for x, y in l: data += [q(x), q(y)]
    print(f"static const uint8_t ICON_{n}[] = {{" + ",".join(map(str, data)) + "};")
print("struct IconDef { const uint8_t *d; uint8_t stroke10; };   // stroke in tenths of a unit")
print("static const IconDef ICONS[] = {{nullptr, 0}, " + ", ".join(f"{{ICON_{n}, {round(s * 10)}}}" for n, s, _ in ICONS) + "};")
print("}  // namespace panel")
